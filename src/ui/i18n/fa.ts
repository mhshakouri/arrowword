/* Persian. Drafted by Claude on 2026-08-05 and owed a native read-through
   (milestone D1's human check): tone is the taste call, not the mechanism.

   Numbers are Persian-Indic digits via `d()`, because Latin digits inside
   Persian prose read as foreign. The one deliberate exception is text a user
   typed (titles, themes, nicknames), which is never reformatted. */

import type { Messages } from "./messages.ts";

/* Not Intl.NumberFormat: these are digit swaps in short strings, and the
   ~۱۲۳۴۵۶۷۸۹۰ mapping is total. Intl would add grouping separators that a
   count of squares does not want. */
const DIGITS = "۰۱۲۳۴۵۶۷۸۹";
const d = (n: number | string): string =>
  String(n).replace(/[0-9]/g, (c) => DIGITS[Number(c)] ?? c);

